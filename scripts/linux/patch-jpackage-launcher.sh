#!/usr/bin/env bash
# Replaces the jpackage native launcher (bin/Nuvio) in a Linux app image with a shell launcher.
#
# The jpackage Linux launcher (seen with JDK 17, 21 and 25) segfaults inside setenv() on glibc 2.43
# before the JVM starts. The shell launcher reads the same lib/app/Nuvio.cfg and starts the bundled
# runtime directly, so classpath, main class and JVM options stay exactly as jpackage wrote them.
#
# Usage: patch-jpackage-launcher.sh <app-root> [java-home]
# java-home defaults to $JAVA_HOME and must be the JDK that produced the bundled runtime.

set -euo pipefail

app_root="${1:?Usage: $0 <app-root> [java-home]}"
java_home="${2:-${JAVA_HOME:-}}"

cfg="$(find "$app_root/lib/app" -maxdepth 1 -name '*.cfg' | head -n 1)"
runtime="$app_root/lib/runtime"
launcher="$(find "$app_root/bin" -maxdepth 1 -type f | head -n 1)"

[[ -f "$cfg" ]] || { echo "No jpackage .cfg under $app_root/lib/app" >&2; exit 1; }
[[ -d "$runtime" ]] || { echo "No bundled runtime at $runtime" >&2; exit 1; }
[[ -n "$launcher" ]] || { echo "No launcher under $app_root/bin" >&2; exit 1; }
[[ -n "$java_home" && -x "$java_home/bin/java" ]] || {
    echo "Set JAVA_HOME (or pass java-home) to the JDK used for packaging." >&2
    exit 1
}

release_version() { sed -n 's/^JAVA_VERSION="\(.*\)"/\1/p' "$1/release"; }
runtime_version="$(release_version "$runtime")"
jdk_version="$(release_version "$java_home")"
if [[ "$runtime_version" != "$jdk_version" ]]; then
    echo "JDK $jdk_version at $java_home does not match bundled runtime $runtime_version." >&2
    exit 1
fi

mkdir -p "$runtime/bin"
install -m 0755 "$java_home/bin/java" "$runtime/bin/java"

main_class=""
classpath=""
java_options=()
section=""
while IFS= read -r line || [[ -n "$line" ]]; do
    case "$line" in
        \[*\]) section="$line"; continue ;;
    esac
    [[ "$section" == "[Application]" || "$section" == "[JavaOptions]" ]] || continue
    key="${line%%=*}"
    value="${line#*=}"
    case "$key" in
        app.mainclass) main_class="$value" ;;
        app.classpath) classpath="${classpath:+$classpath:}$value" ;;
        java-options) java_options+=("$value") ;;
    esac
done < "$cfg"

[[ -n "$main_class" ]] || { echo "No app.mainclass in $cfg" >&2; exit 1; }

# jpackage expands $APPDIR, $BINDIR and $ROOTDIR at launch; the shell launcher defines the same names.
quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
expand_tokens() { printf '%s' "$1" | sed 's/\$APPDIR/${APPDIR}/g; s/\$BINDIR/${BINDIR}/g; s/\$ROOTDIR/${ROOTDIR}/g'; }

options_line=""
for option in "${java_options[@]}"; do
    options_line+=" \"$(expand_tokens "$option" | sed 's/"/\\"/g')\""
done

launcher_tmp="$launcher.tmp"
cat > "$launcher_tmp" <<EOF
#!/bin/sh
# Generated by scripts/linux/patch-jpackage-launcher.sh from $(basename "$cfg").
BINDIR=\$(dirname "\$(readlink -f "\$0")")
ROOTDIR=\$(dirname "\$BINDIR")
APPDIR="\$ROOTDIR/lib/app"
exec "\$ROOTDIR/lib/runtime/bin/java"${options_line} -cp "$(expand_tokens "$classpath")" $(quote "$main_class") "\$@"
EOF
chmod 0755 "$launcher_tmp"
mv "$launcher_tmp" "$launcher"
printf 'Patched launcher: %s\n' "$launcher"
